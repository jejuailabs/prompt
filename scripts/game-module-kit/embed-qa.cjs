const { chromium, options } = require('./browser.cjs');
const assert = require('node:assert/strict'), fs = require('node:fs');
const base = process.env.EMBED_QA_URL || 'http://127.0.0.1:4177';
let browser;
const hostFile = 'public/__coai_embed_qa__.html';
(async () => {
  browser = await chromium.launch(options());
  fs.mkdirSync('tmp/embed-qa', { recursive: true });
  for (const viewport of [{ width: 1280, height: 900 }, { width: 390, height: 780 }]) {
    const ctx = await browser.newContext({ viewport, hasTouch: viewport.width < 500, isMobile: viewport.width < 500, permissions: ['clipboard-read', 'clipboard-write'] });
    const p = await ctx.newPage(), errors = [], posts = [];
    p.setDefaultTimeout(20000);
    p.setDefaultNavigationTimeout(120000);
    p.on('pageerror', error => errors.push(error.message));
    p.on('request', request => { if (request.method() !== 'GET' && new URL(request.url()).pathname.startsWith('/api/')) posts.push(request.url()); });
    await p.route('**/*', route => /^http:\/\/127\.0\.0\.1:(4177|4180)\//.test(route.request().url()) ? route.continue() : route.abort());
    await p.goto(base + '/app#game-play?id=builtin-prism-stack', { timeout: 120000 });
    await p.locator('[data-game-launch]').click();
    const frame = p.frameLocator('iframe');
    await frame.locator('[data-primary]').click({ timeout: 90000 });
    await frame.locator('[data-mute]').click();
    await frame.locator('[data-pause]').click();
    await frame.locator('[data-pause]').click();
    const before = await p.locator('iframe').getAttribute('src');
    if (viewport.width > 500) {
      await p.locator('[data-game-fullscreen]').click();
      await p.waitForFunction(() => Boolean(document.fullscreenElement));
    }
    await p.getByRole('button', { name: '공유 · 퍼가기', exact: true }).click();
    const codeField = p.getByLabel('퍼가기 HTML 코드');
    const code = await codeField.inputValue();
    assert.ok(code.includes('/embed/builtin-prism-stack'));
    await p.getByRole('button', { name: '퍼가기 코드 복사', exact: true }).click();
    assert.equal(await p.evaluate(() => navigator.clipboard.readText()), code);
    await p.screenshot({ path: `tmp/embed-qa/share-${viewport.width}.png` });
    await p.getByRole('dialog').last().getByRole('button', { name: 'Close', exact: true }).click();
    assert.equal(await p.locator('iframe').getAttribute('src'), before, 'sharing preserves the mounted game');
    await p.locator('[data-game-close]').click();
    await p.waitForFunction(() => !document.querySelector('iframe'));
    await p.locator('[data-game-post]').waitFor();
    fs.writeFileSync(hostFile, `<html><body style="margin:0">${code}</body></html>`);
    await p.goto('http://127.0.0.1:4180/__coai_embed_qa__.html');
    await p.frameLocator('iframe').getByLabel('퍼온 작품').waitFor({ timeout: 90000 });
    const nested = p.frameLocator('iframe').frameLocator('iframe');
    await nested.locator('[data-primary]').click({ timeout: 90000 });
    await nested.locator('[data-mute]').click();
    await nested.locator('[data-pause]').click();
    await nested.locator('[data-pause]').click();
    assert.equal(await p.frameLocator('iframe').locator('iframe').getAttribute('sandbox'), null, 'shipped modules retain their resources and storage');
    assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await p.screenshot({ path: `tmp/embed-qa/embedded-${viewport.width}.png` });
    assert.deepEqual(errors, []);
    assert.deepEqual(posts, [], 'no tracking, score, or paid API writes');
    const image = { ...require('../../preview/artifacts.json').data.find(a => a.type === 'image' && a.status === 'published' && a.visibility === 'public'), fileUrl: '/coai/brand/icon.png' };
    await p.route(`**/api/artifacts/${image.id}`, route => route.fulfill({ json: { ok: true, data: image } }));
    await p.route(`**/api/embed/${image.id}`, route => route.fulfill({ json: { ok: true, data: image } }));
    await p.goto(`${base}/app#project?id=${image.id}`);
    await p.getByRole('button', { name: '공유 · 퍼가기', exact: true }).click();
    const imageCode = await p.getByLabel('퍼가기 HTML 코드').inputValue();
    assert.ok((await p.getByLabel('공유 링크').inputValue()).includes('#project?id='));
    fs.writeFileSync(hostFile, `<html><body style="margin:0">${imageCode}</body></html>`);
    await p.goto('http://127.0.0.1:4180/__coai_embed_qa__.html');
    const imageFrame = p.frameLocator('iframe');
    await imageFrame.getByAltText(image.title, { exact: true }).waitFor();
    await imageFrame.getByAltText(image.title, { exact: true }).evaluate(img => img.decode());
    const text = { ...image, id: 'qa-text', type: 'text', description: '긴 결과물 내용입니다.\n'.repeat(200), metadata: {} };
    await p.route('**/api/embed/qa-text', route => route.fulfill({ json: { ok: true, data: text } }));
    await p.goto(`${base}/embed/qa-text`);
    await p.waitForFunction(() => document.querySelector('p')?.textContent?.startsWith('긴 결과물 내용입니다.'));
    assert.equal(await p.locator('p').first().textContent(), text.description);
    const app = { ...image, id: 'qa-app', type: 'app', executionTier: 'iframe', contentUrl: 'https://embed-test.invalid/qa.html', metadata: {} };
    await p.route('**/api/embed/qa-app', route => route.fulfill({ json: { ok: true, data: app } }));
    await p.route('https://embed-test.invalid/qa.html', route => route.fulfill({ contentType: 'text/html; charset=utf-8', body: '<button onclick="this.textContent=\'성공\'">테스트 실행</button>' }));
    await p.goto(`${base}/embed/qa-app`);
    await p.locator('iframe').waitFor();
    await p.frameLocator('iframe').getByRole('button', { name: '테스트 실행' }).click();
    await p.frameLocator('iframe').getByRole('button', { name: '성공' }).waitFor();
    assert.equal(await p.locator('iframe').getAttribute('sandbox'), 'allow-scripts allow-pointer-lock');
    assert.deepEqual(errors, []);
    assert.deepEqual(posts, []);
    await ctx.close();
    console.log(`PASS ${viewport.width}: game/works sharing, clipboard, cross-origin game/image embeds, full text, untrusted app sandbox`);
  }
  await browser.close();
  fs.unlinkSync(hostFile);
})().catch(async error => { console.error(error); await browser?.close(); if (fs.existsSync(hostFile)) fs.unlinkSync(hostFile); process.exitCode = 1; });
